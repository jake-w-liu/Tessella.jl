function _tetrahedron_economical_rule(order::Int)
    table_order=max(order,1)
    1<=table_order<=length(_TETRAHEDRON_ECONOMICAL_COUNTS) || error(
        "MeshQuadrature: internal economical tetrahedron order is invalid")
    point_count=_TETRAHEDRON_ECONOMICAL_COUNTS[table_order]
    coordinates=Vector{Float64}(undef,3point_count)
    weights=Vector{Float64}(undef,point_count)
    first_orbit=_TETRAHEDRON_ORBIT_OFFSETS[table_order]
    orbit_count=_TETRAHEDRON_ORBIT_COUNTS[table_order]
    point_index=0
    for orbit_index in first_orbit:(first_orbit+orbit_count-1)
        orbit=_TETRAHEDRON_ECONOMICAL_ORBITS[orbit_index]
        pattern_index=Int(orbit.pattern)
        1<=pattern_index<=length(_TETRAHEDRON_ORBIT_PATTERNS) || error(
            "MeshQuadrature: invalid economical tetrahedron orbit")
        for (first_value,second_value,third_value) in
            _TETRAHEDRON_ORBIT_PATTERNS[pattern_index]
            point_index+=1
            offset=3(point_index-1)
            coordinates[offset+1]=orbit.values[first_value]
            coordinates[offset+2]=orbit.values[second_value]
            coordinates[offset+3]=orbit.values[third_value]
            weights[point_index]=orbit.weight
        end
    end
    point_index==point_count || error(
        "MeshQuadrature: inconsistent economical tetrahedron table")
    return coordinates,weights
end

