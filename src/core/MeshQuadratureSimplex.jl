function _tetrahedron_lattice_rule(order::Int)
    strength=order÷2
    5<=strength<=10 || error(
        "MeshQuadrature: internal tetrahedron lattice order is invalid")
    point_count=binomial(strength+4,4)
    coordinates=Vector{Float64}(undef,3point_count)
    weights=Vector{Float64}(undef,point_count)
    level_weights=_TETRAHEDRON_LATTICE_WEIGHTS[strength-4]
    point_index=0
    for level in 0:strength
        degree=strength-level
        abscissae=_TETRAHEDRON_LATTICE_ABSCISSAE[degree+1]
        weight=level_weights[level+1]
        for omitted in 0:degree,first in 0:(degree-omitted),
            second in 0:(degree-omitted-first)
            third=degree-omitted-first-second
            point_index+=1
            offset=3(point_index-1)
            coordinates[offset+1]=abscissae[first+1]
            coordinates[offset+2]=abscissae[second+1]
            coordinates[offset+3]=abscissae[third+1]
            weights[point_index]=weight
        end
    end
    point_index==point_count || error(
        "MeshQuadrature: inconsistent tetrahedron lattice table")
    return coordinates,weights
end
