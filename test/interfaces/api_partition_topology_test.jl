checksum(v) = sum(i * Int(x) for (i, x) in enumerate(v); init=0)

function signature()
    rows = []
    for (d, t) in API.model.get_entities()
        n = API.mesh.get_nodes(d, t)[1]
        e = [x for b in API.mesh.get_elements(d, t)[2] for x in b]
        p = API.model.get_parent(d, t)
        b = d > 0 ? [x[2] for x in API.model.get_boundary([(d, t)], false, true)] : Int[]
        push!(rows, (d, t, length(n), checksum(n), length(e), checksum(e), (p[1], p[2]),
                     Int.(API.model.get_partitions(d, t)), Int.(b)))
    end
    return rows
end

expected() = [(r[1], r[2], r[3], r[4], r[5], r[6], r[7], collect(Int, r[8]), collect(Int, r[9])) for r in GMSH]

@testset "partition topology entity by entity as Gmsh" begin
    mktempdir() do dir
        path = joinpath(dir, "cube.msh")
        write(path, MSH)
        API.initialize()
        try
            API.option("General.Terminal", 0)
            API.open(path)
            API.option("Mesh.PartitionCreateTopology", 1)
            API.mesh.partition(3, collect(1:216), [parse(Int, c) for c in SPLIT])
            @test signature() == expected()
        finally
            API.finalize()
        end
    end
end

