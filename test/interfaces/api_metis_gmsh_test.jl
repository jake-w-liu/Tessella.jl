function _partition_string(text,n)
    path=tempname()*".msh"
    write(path,text)
    A.initialize()
    try
        A.open(path)
        p=A._mg_gmsh_partition(n)
        return join(string(p[t]) for t in sort!(collect(keys(p))))
    finally
        A.finalize()
        rm(path;force=true)
    end
end

