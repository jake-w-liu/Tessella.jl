    r=A._MGRand(UInt32(1))
    @test [A._mg_crand!(r) for _ in 1:3]==[41,18467,6334]
    for ((name,n),want) in sort!(collect(EXPECTED))
        text=name=="t21s" ? T21S_MSH : BOXS_MSH
        @test _partition_string(text,n)==want
    end
    # Graph-level entry point: 0-based parts over a 6x6 grid graph.
    nx=6; xadj=Int64[0]; adj=Int64[]
    for j in 0:nx-1, i in 0:nx-1
        for (di,dj) in ((-1,0),(1,0),(0,-1),(0,1))
            (0<=i+di<nx && 0<=j+dj<nx) && push!(adj,(j+dj)*nx+i+di)
        end
        push!(xadj,length(adj))
    end
    part=A._mg_part_graph_recursive(xadj,adj,ones(Int64,nx*nx),4)
    @test sort!(unique(part))==0:3
    @test all(count(==(p),part)==9 for p in 0:3)
