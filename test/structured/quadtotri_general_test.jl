function _cell_faces(c)
    n=length(c)
    n==4 && return [(c[1],c[2],c[3]),(c[1],c[2],c[4]),(c[1],c[3],c[4]),(c[2],c[3],c[4])]
    n==5 && return [(c[1],c[2],c[3],c[4]),(c[1],c[2],c[5]),(c[2],c[3],c[5]),(c[3],c[4],c[5]),(c[4],c[1],c[5])]
    n==6 && return [(c[1],c[2],c[3]),(c[4],c[5],c[6]),(c[1],c[2],c[5],c[4]),(c[2],c[3],c[6],c[5]),(c[3],c[1],c[4],c[6])]
    return [(c[1],c[2],c[3],c[4]),(c[5],c[6],c[7],c[8]),(c[1],c[2],c[6],c[5]),(c[2],c[3],c[7],c[6]),
            (c[3],c[4],c[8],c[7]),(c[4],c[1],c[5],c[8])]
end

@testset "QuadToTri port on Gmsh's mixed source" begin
    key(p)=round.(p;digits=9)
    bypos=Dict(key(p)=>t for (t,p) in _NODES)
    vid=(v,l)->l==0 ? v : bypos[key((_NODES[v][1],_NODES[v][2],_NODES[v][3]+l/3))]
    boundary=Set(v for lines in _LINES for line in lines for v in line)
    region=_Q.QTRegion(_TRIS,_QUADS,[3],vid,v->_NODES[v],boundary,false,_LINES,
        fill(2,4),fill(true,4),false,true,maximum(keys(_NODES))+1)
    result=_Q.qt_mesh_region(region)
    m=result.mesh
    @test (length(m.tets),length(m.hexes),length(m.prisms),length(m.pyramids))==(236,2,7,77)
    @test isempty(m.new_ids)
    # The cells close up: every face is shared by two cells or lies on the
    # source, the top or a remeshed lateral.
    count=Dict{Vector{Int},Int}()
    for cells in (m.tets,m.pyramids,m.prisms,m.hexes),c in cells,f in _cell_faces(c)
        k=sort(collect(f));count[k]=get(count,k,0)+1
    end
    @test all(<=(2),values(count))
    surface=Set{Vector{Int}}(sort(collect(c)) for c in vcat(collect.(_TRIS),collect.(_QUADS)))
    union!(surface,(sort(collect(c)) for c in result.top))
    union!(surface,(sort(collect(c)) for lat in result.laterals for line in lat for c in line))
    @test Set(k for (k,v) in count if v==1)==surface
    @test length(result.top)==7+40
end

@testset "a QuadTriNoNewVerts rotation about an edge of its source" begin
    # Gmsh 4.15.2, 20 fresh processes, all alike: 10 nodes, 14 triangles,
    # 1 quadrangle, 7 tetrahedra and 1 pyramid.
    source="""Point(1)={0,0,0,1};Point(2)={1,0,0,1};Point(3)={1,1,0,1};Point(4)={0,1,0,1};
    Line(1)={1,2};Line(2)={2,3};Line(3)={3,4};Line(4)={4,1};
    Curve Loop(1)={1,2,3,4};Plane Surface(1)={1};
    Transfinite Curve{:}=2;Transfinite Surface{1};Recombine Surface{1};
    sweep[]=Extrude{{0,1,0},{0,0,0},Pi/3}{Surface{1};Layers{3};Recombine;QuadTriNoNewVerts;};
    """
    A=Tessella.API
    A.initialize()
    try
        mktempdir() do directory
            path=joinpath(directory,"hinge.geo")
            write(path,source)
            A.open(path)
            A.mesh.generate(3)
            counts=Dict{Int,Int}()
            for dim in 2:3
                types,tags,_=A.mesh.get_elements(dim)
                for (type,cells) in zip(types,tags)
                    counts[Int(type)]=get(counts,Int(type),0)+length(cells)
                end
            end
            @test length(A.mesh.get_nodes()[1])==10
            @test counts==Dict(2=>14,3=>1,4=>7,7=>1)
            @test validate(A.mesh.get()).ok
        end
    finally
        A.finalize()
    end
end

